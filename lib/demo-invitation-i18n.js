const cache = {};
/** The sample invitation in the given language (falls back to English). */
export function demoInvitationFor(lang) {
  if (!TEXT[lang]) return demoInvitation;
  cache[lang] ??= merge(demoInvitation, TEXT[lang]);
  return cache[lang];
}
